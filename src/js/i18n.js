let currentLang = 'bn';

// Helper function to fetch translation
function t(key, fallback = '') {
  if (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key]) {
    return TRANSLATIONS[currentLang][key];
  }
  if (TRANSLATIONS['en'] && TRANSLATIONS['en'][key]) {
    return TRANSLATIONS['en'][key];
  }
  return fallback || key;
}

// Initialize Language from LocalStorage
function initI18n() {
  const saved = localStorage.getItem('tournament_lang_pref');
  if (saved === 'en' || saved === 'bn') {
    currentLang = saved;
  } else {
    currentLang = 'bn';
  }
  setLanguage(currentLang, false);
}

// Switch Language and Update View
function setLanguage(lang, persist = true) {
  if (lang !== 'bn' && lang !== 'en') return;
  currentLang = lang;
  if (persist) {
    localStorage.setItem('tournament_lang_pref', lang);
  }

  // Update HTML tag attribute
  document.documentElement.lang = lang;

  // Update Switcher Button Active States across all views
  if (typeof document !== 'undefined' && typeof document.querySelectorAll === 'function') {
    document.querySelectorAll('.lang-btn-bn, #btn-lang-bn').forEach(b => {
      if (b && b.classList) b.classList.toggle('active', lang === 'bn');
    });
    document.querySelectorAll('.lang-btn-en, #btn-lang-en').forEach(b => {
      if (b && b.classList) b.classList.toggle('active', lang === 'en');
    });
  }

  // 1. Text Content Translations
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (val) el.textContent = val;
  });

  // 2. HTML Content Translations
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    const val = t(key);
    if (val) el.innerHTML = val;
  });

  // 3. Placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const val = t(key);
    if (val) el.placeholder = val;
  });

  // 4. Tooltips (Title)
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const val = t(key);
    if (val) el.title = val;
  });

  // 5. Update Dynamic Engine Views
  if (typeof applyTournamentConfig === 'function') {
    applyTournamentConfig();
  }
  if (typeof renderPage2RulesList === 'function') {
    renderPage2RulesList();
  }
  if (typeof recalculateAll === 'function') {
    recalculateAll();
  }
  if (typeof switchRosterTeam === 'function' && typeof currentRosterTeam !== 'undefined') {
    switchRosterTeam(currentRosterTeam);
  }
  if (typeof updateSheetThemeButtonText === 'function') {
    updateSheetThemeButtonText();
  }
  if (typeof updateHubFootballCard === 'function') {
    updateHubFootballCard();
  }
  if (typeof updateNavWizardButton === 'function') {
    updateNavWizardButton();
  }
  if (typeof renderWizardFormatSuggestions === 'function') {
    renderWizardFormatSuggestions();
  }

  // If Wizard is active, re-render rules checklist in the chosen language
  const wizardModal = document.getElementById('tournament-wizard-modal');
  if (wizardModal && wizardModal.classList.contains('active') && typeof renderWizardRulesChecklist === 'function') {
    renderWizardRulesChecklist(document.getElementById('w-rules-search-input')?.value || '');
  }

  // If Promo Poster is active, re-render poster
  const promoModal = document.getElementById('promo-poster-modal');
  if (promoModal && promoModal.classList.contains('active') && typeof openPromoPosterModal === 'function') {
    openPromoPosterModal();
  }
}
